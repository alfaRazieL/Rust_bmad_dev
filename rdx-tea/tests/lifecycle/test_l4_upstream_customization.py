"""L4 real upstream customization proof (Phase C of the D3 proof).

Runs the ACTUAL upstream `resolve_customization.py` script against a
disposable directory tree that mimics an installed BMAD 6.8.0 + TEA
v1.19.0 project, with an RDX-TEA overlay written per ADR-002.

The resolver script is loaded from the upstream clone at
`rdx-workspace/upstream/BMAD-METHOD` (locked SHA in
`D3_SOURCE_LOCK_ADDENDUM.md §1.1`).

Every assertion below is grounded in an actual JSON output from the
resolver, not a mock.
"""

from __future__ import annotations

import os
import sys
import json
import shutil
import subprocess
from pathlib import Path

import pytest

RDX_TEA_DIR = Path(__file__).resolve().parent.parent.parent
REPO_ROOT = RDX_TEA_DIR.parent
UPSTREAM_ROOT = Path(os.environ.get("RDX_TEA_UPSTREAM_ROOT", str(REPO_ROOT.parent / "upstream")))
WORKSPACE = UPSTREAM_ROOT.parent
UPSTREAM_TEA = UPSTREAM_ROOT / "bmad-method-test-architecture-enterprise"
UPSTREAM_BMAD = UPSTREAM_ROOT / "BMAD-METHOD"
VENV_PY = Path(sys.executable)

# The upstream resolve_customization.py at BMAD v6.8.0 tag.
RESOLVER = UPSTREAM_BMAD / "src" / "scripts" / "resolve_customization.py"
UPSTREAM_TESTARCH_TESTDESIGN = (
    UPSTREAM_TEA / "src" / "workflows" / "testarch" / "bmad-testarch-test-design"
)


@pytest.fixture(scope="module")
def upstream_present() -> None:
    if not RESOLVER.exists():
        pytest.skip(f"upstream resolver missing at {RESOLVER}")
    if not UPSTREAM_TESTARCH_TESTDESIGN.exists():
        pytest.skip(f"upstream TEA skill missing at {UPSTREAM_TESTARCH_TESTDESIGN}")


@pytest.fixture
def disposable_project(tmp_path: Path, upstream_present) -> Path:
    """A `{project-root}` with `_bmad/custom/` and a skill under
    `.claude/skills/bmad-testarch-test-design/` copied from upstream."""
    proj = tmp_path / "proj"
    proj.mkdir()
    (proj / "_bmad").mkdir()
    (proj / "_bmad" / "custom").mkdir()
    # Copy skill root from upstream.
    skill_dst = proj / ".claude" / "skills" / "bmad-testarch-test-design"
    shutil.copytree(UPSTREAM_TESTARCH_TESTDESIGN, skill_dst)
    return proj


def _write_rdx_tea_overlay(proj: Path, extra_user_overlay: bool = False) -> None:
    """Write the ADR-002-compliant `_bmad/custom/bmad-testarch-test-design.toml`
    overlay."""
    overlay = proj / "_bmad" / "custom" / "bmad-testarch-test-design.toml"
    overlay.write_text('''# RDX-TEA overlay for bmad-testarch-test-design.
# Generated by rdx-tea-setup (ADR-002 §5.6 wrapper).
# DO NOT EDIT — regenerate via `python3 -m rdx_tea.setup install`.

[workflow]

# Prepend runs BEFORE persistent_facts (verified against upstream
# bmad-testarch-test-design/SKILL.md §"On Activation" Step 2 → Step 3).
activation_steps_prepend = [
  "Run: python3 {project-root}/_bmad/rdx-tea/scripts/prepare.py --workflow test-design --project-root {project-root}. HALT on non-zero exit.",
]

# persistent_facts references the stable active-context bundle written
# by the prepend step. The path is deterministic per (workflow, project).
persistent_facts = [
  "file:{project-root}/_bmad/rdx-tea/runtime/test-design/active-context.md",
]

# Sidecar binder runs AS THE FINAL TERMINAL INSTRUCTION per upstream
# bmad-testarch-test-design/steps-c/step-05-generate-output.md:232-236.
on_complete = "Run: python3 {project-root}/_bmad/rdx-tea/scripts/binder.py --workflow test-design --project-root {project-root}"
''')
    if extra_user_overlay:
        user = proj / "_bmad" / "custom" / "bmad-testarch-test-design.user.toml"
        user.write_text('''[workflow]

persistent_facts = [
  "The developer prefers Playwright over Cypress for E2E.",
]
''')


def _run_resolver(proj: Path, skill_dir: Path, key: str = "workflow") -> dict:
    """Invoke upstream `resolve_customization.py` and return the merged
    `workflow` block (unwrapped from the resolver's outer envelope)."""
    result = subprocess.run(
        [str(VENV_PY), str(RESOLVER),
         "--skill", str(skill_dir),
         "--key", key],
        cwd=str(proj),
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        pytest.fail(
            f"resolver exited {result.returncode}\n"
            f"stdout: {result.stdout}\nstderr: {result.stderr}"
        )
    raw = json.loads(result.stdout)
    # The resolver wraps the merged block in {"workflow": {...}} when
    # `--key workflow` is used. Unwrap for convenience.
    if isinstance(raw, dict) and key in raw and isinstance(raw[key], dict):
        return raw[key]
    return raw


