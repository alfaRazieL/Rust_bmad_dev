def test_l4_c01_upstream_resolver_returns_prepend_command(disposable_project: Path) -> None:
    _write_rdx_tea_overlay(disposable_project)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    merged = _run_resolver(disposable_project, skill)
    prepend = merged.get("activation_steps_prepend") or []
    assert any(
        "prepare.py" in step and "--workflow test-design" in step
        for step in prepend
    ), f"prepend step missing prepare.py invocation: {prepend}"


def test_l4_c02_upstream_resolver_returns_active_context_bundle_path(disposable_project: Path) -> None:
    _write_rdx_tea_overlay(disposable_project)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    merged = _run_resolver(disposable_project, skill)
    facts = merged.get("persistent_facts") or []
    assert any(
        "_bmad/rdx-tea/runtime/test-design/active-context.md" in f
        for f in facts
    ), f"active-context bundle path not merged into persistent_facts: {facts}"


def test_l4_c03_upstream_resolver_returns_on_complete_binder(disposable_project: Path) -> None:
    _write_rdx_tea_overlay(disposable_project)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    merged = _run_resolver(disposable_project, skill)
    on_complete = merged.get("on_complete", "")
    assert "binder.py" in on_complete, (
        f"on_complete did not include binder invocation: {on_complete!r}"
    )
    assert "--workflow test-design" in on_complete


def test_l4_c04_upstream_resolver_preserves_base_persistent_facts(disposable_project: Path) -> None:
    """The upstream base `file:{project-root}/**/project-context.md` glob
    is not clobbered by our overlay (append semantics)."""
    _write_rdx_tea_overlay(disposable_project)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    merged = _run_resolver(disposable_project, skill)
    facts = merged.get("persistent_facts") or []
    assert any("project-context.md" in f for f in facts), (
        f"base persistent_facts entry lost after RDX overlay merge: {facts}"
    )


def test_l4_c05_upstream_resolver_preserves_user_override(disposable_project: Path) -> None:
    """A `.user.toml` overlay appends AFTER the team overlay and MUST NOT
    be clobbered."""
    _write_rdx_tea_overlay(disposable_project, extra_user_overlay=True)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    merged = _run_resolver(disposable_project, skill)
    facts = merged.get("persistent_facts") or []
    assert any("Playwright" in f for f in facts), (
        f"user overlay lost: {facts}"
    )


def test_l4_c06_upstream_resolver_produces_valid_toml_shape(disposable_project: Path) -> None:
    """No duplicate `[workflow]` tables, no NULs, well-formed dict."""
    _write_rdx_tea_overlay(disposable_project)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    merged = _run_resolver(disposable_project, skill)
    assert isinstance(merged, dict)
    # A `[workflow]` block that got merged twice (the historic bug) would
    # produce keys nested wrong. Check we have flat expected keys.
    for k in ("activation_steps_prepend", "persistent_facts", "on_complete"):
        assert k in merged, f"missing top-level key {k}"


def test_l4_c07_no_skill_root_modifications(disposable_project: Path) -> None:
    """After a full resolve, the upstream skill directory must be
    byte-identical to the pristine copy."""
    _write_rdx_tea_overlay(disposable_project, extra_user_overlay=True)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    _ = _run_resolver(disposable_project, skill)
    # Compare each file byte-for-byte.
    import hashlib
    for pristine in UPSTREAM_TESTARCH_TESTDESIGN.rglob("*"):
        if not pristine.is_file():
            continue
        rel = pristine.relative_to(UPSTREAM_TESTARCH_TESTDESIGN)
        candidate = skill / rel
        assert candidate.exists(), f"skill lost {rel}"
        assert (
            hashlib.sha256(pristine.read_bytes()).hexdigest()
            == hashlib.sha256(candidate.read_bytes()).hexdigest()
        ), f"skill file mutated: {rel}"


def test_l4_c08_resolver_exit_code_is_zero(disposable_project: Path) -> None:
    """Sanity: the resolver must exit 0 for a well-formed overlay."""
    _write_rdx_tea_overlay(disposable_project)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    result = subprocess.run(
        [str(VENV_PY), str(RESOLVER),
         "--skill", str(skill), "--key", "workflow"],
        cwd=str(disposable_project),
        capture_output=True, text=True,
    )
    assert result.returncode == 0, f"stderr: {result.stderr}"


def test_l4_c09_resolver_output_is_reproducible(disposable_project: Path) -> None:
    """Two consecutive invocations produce identical JSON."""
    _write_rdx_tea_overlay(disposable_project)
    skill = disposable_project / ".claude" / "skills" / "bmad-testarch-test-design"
    a = _run_resolver(disposable_project, skill)
    b = _run_resolver(disposable_project, skill)
    assert a == b
